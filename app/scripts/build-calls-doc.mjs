// Writes docs/BACKEND-CALLS.md: every place the window calls the backend, and whether that file shows a waiting state.
// Run: node scripts/build-calls-doc.mjs   (npm test fails when the page is out of date)

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const UI = join(APP, "ui");
const DOC = join(APP, "..", "docs", "BACKEND-CALLS.md");

// What counts as a waiting state: the shared loader, a busy or loaded flag, or a disabled control while a call runs.
const WAITS =
  /<Loading\b|\b[a-zA-Z]*[Bb]usy\b|\bloaded\b|\bloading\b|Checking…|Opening…|Sending…/;

function files(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? files(join(dir, entry.name))
        : /\.(svelte|ts)$/.test(entry.name)
          ? [join(dir, entry.name)]
          : [],
    )
    .sort();
}

export function listCalls() {
  return files(UI).flatMap((path) => {
    const text = readFileSync(path, "utf8");
    if (!text.includes("sidecar_call")) return [];
    const methods = [
      ...new Set([...text.matchAll(/method:\s*"([a-z_]+)"/g)].map((m) => m[1])),
    ].sort();
    return [
      {
        file: relative(APP, path).replaceAll("\\", "/"),
        methods,
        waits: WAITS.test(text),
      },
    ];
  });
}

export function buildCallsDoc(rows = listCalls()) {
  const without = rows.filter((row) => !row.waits);
  return [
    "# Backend calls made by the window",
    "",
    "Generated by `app/scripts/build-calls-doc.mjs`. Do not edit by hand: run `node scripts/build-calls-doc.mjs` in `app/`.",
    "",
    `${rows.length} files call the backend. ${rows.length - without.length} show a waiting state (the shared loader, a busy or loaded flag); ${without.length} do not yet.`,
    "A name the file builds at run time is not listed.",
    "",
    "| File | Methods | Waiting state |",
    "|---|---|---|",
    ...rows.map(
      (row) =>
        `| \`${row.file}\` | ${row.methods.map((m) => `\`${m}\``).join(", ") || "(built at run time)"} | ${row.waits ? "yes" : "no"} |`,
    ),
    "",
  ].join("\n");
}

export function readCallsDoc() {
  try {
    return readFileSync(DOC, "utf8");
  } catch {
    return "";
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(DOC, buildCallsDoc());
  console.log(`wrote ${relative(APP, DOC)}`);
}
