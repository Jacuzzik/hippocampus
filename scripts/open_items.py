"""Rebuilds docs/WORKER-OPEN-ITEMS.md: every plan item in docs/PHASE.md whose id is not named in docs/PHASE-progress.md.

Run from the repository root: `uv run python scripts/open_items.py`. An item is closed by naming its id
in a row of docs/PHASE-progress.md, never by editing the open-items file.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {
    "1": "Bugs found in the app", "2": "Errors and first run", "3": "Design tokens and shared components",
    "4": "Layout", "5": "Buttons and controls", "6": "Fonts", "7": "Reference feature set", "8": "Briefings",
    "9": "Inbox", "11": "Backend", "12": "Motion", "13": "Loading states",
    "14": "Accounts (blocked: owner decision)", "15": "Website", "A": "Stability", "B": "Performance",
    "C": "Tests and CI", "D": "Decisions", "E": "Accessibility", "F": "Security", "G": "Install and release",
    "H": "Languages", "I": "Documents", "J": "Graph", "K": "Connectors", "L": "Control Room tabs",
    "M": "Settings", "N": "New features",
}  # fmt: skip


def order(item: str) -> tuple[int, int, int]:
    section, number = item.split(".")
    return (0, int(section), int(number)) if section.isdigit() else (1, ord(section), int(number))


def main() -> None:
    phase = (ROOT / "docs" / "PHASE.md").read_text(encoding="utf-8")
    progress = (ROOT / "docs" / "PHASE-progress.md").read_text(encoding="utf-8")
    items: dict[str, str] = {}
    for item, text in re.findall(r"^- \*\*([0-9A-N]+\.\d+)\*\* (.*)$", phase, re.M):
        items.setdefault(item, text.strip())
    closed = set(re.findall(r"\b([0-9]{1,2}\.\d{2}|[A-N]\.\d{2})\b", progress))
    for first, last in re.findall(r"(\d+\.\d{2}) to (\d+\.\d{2})", progress):
        section, low = first.split(".")
        closed |= {f"{section}.{n:02d}" for n in range(int(low), int(last.split(".")[1]) + 1)}
    still_open = [item for item in sorted(items, key=order) if item not in closed]
    lines = [
        "# Open items",
        "",
        f"{len(still_open)} of {len(items)} plan items are open. Made from `docs/PHASE.md` minus every id named in `docs/PHASE-progress.md`.",
        "The text of each row is cut short here; the full wording is in `docs/PLAN-text.txt` (search for the id at the start of a line).",
        "Rules for working through this list are in `docs/WORKER-GUIDE.md`. Do not edit this file by hand: run `uv run python scripts/open_items.py`.",
    ]
    section = None
    for item in still_open:
        if item.split(".")[0] != section:
            section = item.split(".")[0]
            lines += ["", f"## {section}. {NAMES.get(section, '')}", ""]
        lines.append(f"- [ ] **{item}** {items[item]}")
    (ROOT / "docs" / "WORKER-OPEN-ITEMS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(still_open)} of {len(items)} open")


if __name__ == "__main__":
    main()
